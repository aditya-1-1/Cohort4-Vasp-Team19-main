import Foundation
import UIKit

/// Generates a complete, multi-page PDF evaluation report from an interview rehearsal.
@MainActor
final class PDFReportGenerator {
    static func createPDF(for rehearsal: Rehearsal) -> URL? {
        let pageWidth: CGFloat = 612 // US Letter width: 8.5 x 72 pt
        let pageHeight: CGFloat = 792 // US Letter height: 11 x 72 pt
        let margin: CGFloat = 40
        let contentWidth = pageWidth - (margin * 2)

        let pdfMetaData = [
            kCGPDFContextCreator: "Rehearse AI Interview Coach",
            kCGPDFContextAuthor: "Rehearse",
            kCGPDFContextTitle: "\(rehearsal.title) - Interview Performance Report"
        ]
        let format = UIGraphicsPDFRendererFormat()
        format.documentInfo = pdfMetaData as [String: Any]

        let renderer = UIGraphicsPDFRenderer(bounds: CGRect(x: 0, y: 0, width: pageWidth, height: pageHeight), format: format)

        let filename = "Rehearse_Report_\(rehearsal.title.replacingOccurrences(of: " ", with: "_")).pdf"
        let tempURL = FileManager.default.temporaryDirectory.appendingPathComponent(filename)

        do {
            try renderer.writePDF(to: tempURL) { context in
                var currentY: CGFloat = margin
                var pageNumber = 1

                func startPage() {
                    context.beginPage()
                    currentY = margin

                    // Top brand header
                    let logoAttrs: [NSAttributedString.Key: Any] = [
                        .font: UIFont.systemFont(ofSize: 16, weight: .black),
                        .foregroundColor: UIColor(red: 0.93, green: 0.35, blue: 0.14, alpha: 1.0)
                    ]
                    ("REHEARSE" as NSString).draw(at: CGPoint(x: margin, y: currentY), withAttributes: logoAttrs)

                    let subAttrs: [NSAttributedString.Key: Any] = [
                        .font: UIFont.systemFont(ofSize: 10, weight: .semibold),
                        .foregroundColor: UIColor.systemGray
                    ]
                    ("INTERVIEW PERFORMANCE & EVALUATION REPORT" as NSString).draw(at: CGPoint(x: margin + 98, y: currentY + 4), withAttributes: subAttrs)

                    currentY += 28

                    // Divider line
                    let path = UIBezierPath()
                    path.move(to: CGPoint(x: margin, y: currentY))
                    path.addLine(to: CGPoint(x: pageWidth - margin, y: currentY))
                    UIColor.systemGray4.setStroke()
                    path.lineWidth = 1
                    path.stroke()

                    currentY += 18
                }

                func checkPage(neededHeight: CGFloat) {
                    if currentY + neededHeight > pageHeight - margin - 24 {
                        drawFooter(page: pageNumber)
                        pageNumber += 1
                        startPage()
                    }
                }

                func drawFooter(page: Int) {
                    let footerAttrs: [NSAttributedString.Key: Any] = [
                        .font: UIFont.systemFont(ofSize: 9, weight: .regular),
                        .foregroundColor: UIColor.systemGray2
                    ]
                    let footerText = "Generated by Rehearse • rehearse.app"
                    (footerText as NSString).draw(at: CGPoint(x: margin, y: pageHeight - margin + 6), withAttributes: footerAttrs)

                    let pageText = "Page \(page)"
                    let pageTextSize = (pageText as NSString).size(withAttributes: footerAttrs)
                    (pageText as NSString).draw(at: CGPoint(x: pageWidth - margin - pageTextSize.width, y: pageHeight - margin + 6), withAttributes: footerAttrs)
                }

                // Page 1 start
                startPage()

                // Interview Title & Subtitle
                let titleAttrs: [NSAttributedString.Key: Any] = [
                    .font: UIFont.systemFont(ofSize: 22, weight: .bold),
                    .foregroundColor: UIColor.label
                ]
                let titleRect = CGRect(x: margin, y: currentY, width: contentWidth, height: 28)
                (rehearsal.title as NSString).draw(in: titleRect, withAttributes: titleAttrs)
                currentY += 30

                let dateSubtitle = "\(rehearsal.subtitle.capitalized) • \(rehearsal.date.formatted(date: .abbreviated, time: .shortened))"
                let dateAttrs: [NSAttributedString.Key: Any] = [
                    .font: UIFont.systemFont(ofSize: 11, weight: .regular),
                    .foregroundColor: UIColor.secondaryLabel
                ]
                (dateSubtitle as NSString).draw(at: CGPoint(x: margin, y: currentY), withAttributes: dateAttrs)
                currentY += 24

                // Score Card Box
                if let feedback = rehearsal.feedback {
                    checkPage(neededHeight: 84)
                    let scoreBoxRect = CGRect(x: margin, y: currentY, width: contentWidth, height: 74)
                    let boxPath = UIBezierPath(roundedRect: scoreBoxRect, cornerRadius: 8)
                    UIColor.systemGray6.setFill()
                    boxPath.fill()
                    UIColor.systemGray4.setStroke()
                    boxPath.lineWidth = 1
                    boxPath.stroke()

                    // Big Score
                    let scoreString = "\(feedback.overall)"
                    let scoreAttrs: [NSAttributedString.Key: Any] = [
                        .font: UIFont.systemFont(ofSize: 36, weight: .heavy),
                        .foregroundColor: UIColor(red: 0.93, green: 0.35, blue: 0.14, alpha: 1.0)
                    ]
                    (scoreString as NSString).draw(at: CGPoint(x: margin + 18, y: currentY + 14), withAttributes: scoreAttrs)

                    let scoreWidth = (scoreString as NSString).size(withAttributes: scoreAttrs).width
                    let outOfAttrs: [NSAttributedString.Key: Any] = [
                        .font: UIFont.systemFont(ofSize: 12, weight: .bold),
                        .foregroundColor: UIColor.secondaryLabel
                    ]
                    ("/ 100" as NSString).draw(at: CGPoint(x: margin + 22 + scoreWidth, y: currentY + 30), withAttributes: outOfAttrs)

                    let bandTitle = feedback.band.title
                    let bandAttrs: [NSAttributedString.Key: Any] = [
                        .font: UIFont.systemFont(ofSize: 18, weight: .bold),
                        .foregroundColor: UIColor.label
                    ]
                    (bandTitle as NSString).draw(at: CGPoint(x: margin + 140, y: currentY + 16), withAttributes: bandAttrs)

                    let bandDesc = "Overall Interview Performance"
                    (bandDesc as NSString).draw(at: CGPoint(x: margin + 140, y: currentY + 42), withAttributes: dateAttrs)

                    currentY += 90

                    // Evaluation Summary
                    if !feedback.summary.isEmpty {
                        checkPage(neededHeight: 80)
                        let secTitleAttrs: [NSAttributedString.Key: Any] = [
                            .font: UIFont.systemFont(ofSize: 13, weight: .bold),
                            .foregroundColor: UIColor.label
                        ]
                        ("Evaluation Summary" as NSString).draw(at: CGPoint(x: margin, y: currentY), withAttributes: secTitleAttrs)
                        currentY += 18

                        let summaryAttrs: [NSAttributedString.Key: Any] = [
                            .font: UIFont.systemFont(ofSize: 10.5, weight: .regular),
                            .foregroundColor: UIColor.label
                        ]
                        let summaryBounds = (feedback.summary as NSString).boundingRect(
                            with: CGSize(width: contentWidth, height: 250),
                            options: [.usesLineFragmentOrigin, .usesFontLeading],
                            attributes: summaryAttrs,
                            context: nil
                        )
                        (feedback.summary as NSString).draw(in: CGRect(x: margin, y: currentY, width: contentWidth, height: summaryBounds.height + 4), withAttributes: summaryAttrs)
                        currentY += summaryBounds.height + 16
                    }

                    // Score Breakdown
                    checkPage(neededHeight: 110)
                    let bdTitleAttrs: [NSAttributedString.Key: Any] = [
                        .font: UIFont.systemFont(ofSize: 13, weight: .bold),
                        .foregroundColor: UIColor.label
                    ]
                    ("Score Breakdown by Evaluation Area" as NSString).draw(at: CGPoint(x: margin, y: currentY), withAttributes: bdTitleAttrs)
                    currentY += 18

                    for area in feedback.areas {
                        checkPage(neededHeight: 26)
                        let areaNameAttrs: [NSAttributedString.Key: Any] = [
                            .font: UIFont.systemFont(ofSize: 10.5, weight: .semibold),
                            .foregroundColor: UIColor.label
                        ]
                        (area.area.title as NSString).draw(at: CGPoint(x: margin, y: currentY), withAttributes: areaNameAttrs)

                        let areaScoreStr = "\(area.score) / 100"
                        let areaScoreAttrs: [NSAttributedString.Key: Any] = [
                            .font: UIFont.systemFont(ofSize: 10.5, weight: .bold),
                            .foregroundColor: UIColor(red: 0.93, green: 0.35, blue: 0.14, alpha: 1.0)
                        ]
                        let scoreWidth = (areaScoreStr as NSString).size(withAttributes: areaScoreAttrs).width
                        (areaScoreStr as NSString).draw(at: CGPoint(x: pageWidth - margin - scoreWidth, y: currentY), withAttributes: areaScoreAttrs)

                        let barY = currentY + 16
                        let barRect = CGRect(x: margin, y: barY, width: contentWidth, height: 4)
                        let barBg = UIBezierPath(roundedRect: barRect, cornerRadius: 2)
                        UIColor.systemGray5.setFill()
                        barBg.fill()

                        let fillWidth = max(4, contentWidth * (CGFloat(area.score) / 100.0))
                        let fillRect = CGRect(x: margin, y: barY, width: fillWidth, height: 4)
                        let fillPath = UIBezierPath(roundedRect: fillRect, cornerRadius: 2)
                        UIColor(red: 0.93, green: 0.35, blue: 0.14, alpha: 1.0).setFill()
                        fillPath.fill()

                        currentY += 26
                    }
                    currentY += 8

                    // Key Strengths
                    if !feedback.strengths.isEmpty {
                        checkPage(neededHeight: 60)
                        let strTitleAttrs: [NSAttributedString.Key: Any] = [
                            .font: UIFont.systemFont(ofSize: 13, weight: .bold),
                            .foregroundColor: UIColor(red: 0.15, green: 0.65, blue: 0.35, alpha: 1.0)
                        ]
                        ("Key Strengths" as NSString).draw(at: CGPoint(x: margin, y: currentY), withAttributes: strTitleAttrs)
                        currentY += 18

                        for strength in feedback.strengths {
                            checkPage(neededHeight: 28)
                            let bullet = "•  \(strength)"
                            let bulletAttrs: [NSAttributedString.Key: Any] = [
                                .font: UIFont.systemFont(ofSize: 10, weight: .regular),
                                .foregroundColor: UIColor.label
                            ]
                            let bounds = (bullet as NSString).boundingRect(
                                with: CGSize(width: contentWidth, height: 120),
                                options: [.usesLineFragmentOrigin, .usesFontLeading],
                                attributes: bulletAttrs,
                                context: nil
                            )
                            (bullet as NSString).draw(in: CGRect(x: margin, y: currentY, width: contentWidth, height: bounds.height + 2), withAttributes: bulletAttrs)
                            currentY += bounds.height + 6
                        }
                        currentY += 8
                    }

                    // What to Improve
                    if !feedback.focusEvidence.isEmpty {
                        checkPage(neededHeight: 50)
                        let focusTitleAttrs: [NSAttributedString.Key: Any] = [
                            .font: UIFont.systemFont(ofSize: 13, weight: .bold),
                            .foregroundColor: UIColor(red: 0.93, green: 0.35, blue: 0.14, alpha: 1.0)
                        ]
                        ("Primary Focus for Improvement: \(feedback.focus.title)" as NSString).draw(at: CGPoint(x: margin, y: currentY), withAttributes: focusTitleAttrs)
                        currentY += 18

                        let focusAttrs: [NSAttributedString.Key: Any] = [
                            .font: UIFont.systemFont(ofSize: 10, weight: .regular),
                            .foregroundColor: UIColor.label
                        ]
                        let bounds = (feedback.focusEvidence as NSString).boundingRect(
                            with: CGSize(width: contentWidth, height: 140),
                            options: [.usesLineFragmentOrigin, .usesFontLeading],
                            attributes: focusAttrs,
                            context: nil
                        )
                        (feedback.focusEvidence as NSString).draw(in: CGRect(x: margin, y: currentY, width: contentWidth, height: bounds.height + 2), withAttributes: focusAttrs)
                        currentY += bounds.height + 16
                    }
                }

                // Question & Answer Transcripts
                if !rehearsal.transcript.isEmpty {
                    checkPage(neededHeight: 40)
                    let transSecAttrs: [NSAttributedString.Key: Any] = [
                        .font: UIFont.systemFont(ofSize: 14, weight: .bold),
                        .foregroundColor: UIColor.label
                    ]
                    ("Interview Questions & Answer Details" as NSString).draw(at: CGPoint(x: margin, y: currentY), withAttributes: transSecAttrs)
                    currentY += 20

                    for (idx, entry) in rehearsal.transcript.enumerated() {
                        checkPage(neededHeight: 100)

                        let qHeader = "Question \(idx + 1)\(entry.isFollowUp ? " (Follow-up)" : "")"
                        let qHeaderAttrs: [NSAttributedString.Key: Any] = [
                            .font: UIFont.systemFont(ofSize: 11, weight: .bold),
                            .foregroundColor: UIColor(red: 0.93, green: 0.35, blue: 0.14, alpha: 1.0)
                        ]
                        (qHeader as NSString).draw(at: CGPoint(x: margin, y: currentY), withAttributes: qHeaderAttrs)
                        currentY += 16

                        let qTextAttrs: [NSAttributedString.Key: Any] = [
                            .font: UIFont.systemFont(ofSize: 10.5, weight: .semibold),
                            .foregroundColor: UIColor.label
                        ]
                        let qBounds = (entry.question as NSString).boundingRect(
                            with: CGSize(width: contentWidth, height: 120),
                            options: [.usesLineFragmentOrigin, .usesFontLeading],
                            attributes: qTextAttrs,
                            context: nil
                        )
                        (entry.question as NSString).draw(in: CGRect(x: margin, y: currentY, width: contentWidth, height: qBounds.height + 2), withAttributes: qTextAttrs)
                        currentY += qBounds.height + 8

                        checkPage(neededHeight: 50)
                        let aHeader = "Candidate Answer:"
                        let aHeaderAttrs: [NSAttributedString.Key: Any] = [
                            .font: UIFont.systemFont(ofSize: 9.5, weight: .bold),
                            .foregroundColor: UIColor.secondaryLabel
                        ]
                        (aHeader as NSString).draw(at: CGPoint(x: margin, y: currentY), withAttributes: aHeaderAttrs)
                        currentY += 12

                        let aTextAttrs: [NSAttributedString.Key: Any] = [
                            .font: UIFont.systemFont(ofSize: 9.5, weight: .regular),
                            .foregroundColor: UIColor.label
                        ]
                        let aBounds = (entry.answer as NSString).boundingRect(
                            with: CGSize(width: contentWidth, height: 160),
                            options: [.usesLineFragmentOrigin, .usesFontLeading],
                            attributes: aTextAttrs,
                            context: nil
                        )
                        (entry.answer as NSString).draw(in: CGRect(x: margin, y: currentY, width: contentWidth, height: aBounds.height + 2), withAttributes: aTextAttrs)
                        currentY += aBounds.height + 10

                        if let eval = entry.evaluation {
                            checkPage(neededHeight: 45)
                            let evalNote = "Evaluation (\(eval.scoreOutOf100)/100 - \(eval.evaluation_result.score_label)): \(eval.evaluation_result.feedback.summary)"
                            let evalAttrs: [NSAttributedString.Key: Any] = [
                                .font: UIFont.systemFont(ofSize: 9, weight: .medium),
                                .foregroundColor: UIColor.secondaryLabel
                            ]
                            let eBounds = (evalNote as NSString).boundingRect(
                                with: CGSize(width: contentWidth, height: 120),
                                options: [.usesLineFragmentOrigin, .usesFontLeading],
                                attributes: evalAttrs,
                                context: nil
                            )
                            (evalNote as NSString).draw(in: CGRect(x: margin, y: currentY, width: contentWidth, height: eBounds.height + 2), withAttributes: evalAttrs)
                            currentY += eBounds.height + 12
                        }

                        let qDivider = UIBezierPath()
                        qDivider.move(to: CGPoint(x: margin, y: currentY))
                        qDivider.addLine(to: CGPoint(x: pageWidth - margin, y: currentY))
                        UIColor.systemGray5.setStroke()
                        qDivider.lineWidth = 0.5
                        qDivider.stroke()
                        currentY += 14
                    }
                }

                // Final footer
                drawFooter(page: pageNumber)
            }
            return tempURL
        } catch {
            print("[PDFReportGenerator] Error generating PDF: \(error)")
            return nil
        }
    }
}
